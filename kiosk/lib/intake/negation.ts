/**
 * red flag 키워드 매칭을 위한 한국어 부정 처리.
 *
 * 해결하려는 문제: red flag 패턴은 극성(polarity) 개념이 없는 키워드 정규식이다.
 * "다친 적은 없습니다" 에는 다친 이 들어 있으므로, 외상을 명시적으로 부정한
 * 환자에게 외상 패턴이 발화한다. 그러면 의사는 일어난 적 없는 부상을 주장하는
 * 배너를 읽게 되는데, 이건 배너가 없느니만 못하다 — 상습적으로 틀리는 이유
 * 문자열은 곧 읽히지 않게 된다.
 *
 * 접근은 일부러 좁다. 절(clause)은 명백한 한국어 부정 서술어(없습니다 /
 * 않았어요 / 아니요 / 못 들었어요 등)로 끝날 때만 제거된다. 그 정밀함은
 * 양방향으로 중요하다:
 *
 *   * 절 끝에 앵커를 두면 "시력이 없어졌어요" 는 없어 를 포함하는데도 부정
 *     집합에 들어가지 않는다. 그 문장은 응급이고, 느슨한 부분문자열 규칙이라면
 *     조용히 지워버렸을 것이다.
 *   * 부정된 절만 제거한다. 나머지는 다시 이어붙이므로
 *     "고혈압으로 약을 먹고 있고, 당뇨는 없습니다" 는 여전히 고혈압 을 남긴다.
 *
 * 남는 위험은 과잉 마스킹이다. 그건 모델의 danger 신호가 경계한다 — 그쪽은
 * 원문 그대로 평가되고 마스킹되지 않으므로, 놓친 키워드가 곧 놓친 응급은 아니다.
 */

/**
 * 절 경계: 문장 종결 부호와, 한국어 구어가 별개 주장을 이어붙일 때 쓰는
 * 쉼표류 연결. 쉼표에서 쪼개야 긴 답변 안의 부정 하나만 떨어져 나간다.
 */
const CLAUSE_BOUNDARY = /[.!?。\n,;]+/;

/** 부정 판정 전에 벗겨내는 꼬리 조사·문장부호. "없습니다." 와 "없습니다" 를 같게. */
const TRAILING_NOISE = /[\s.!?~…"'”’)\]】]+$/;

/**
 * 절 끝에 앵커된 부정 서술어.
 *
 * 앵커가 핵심이다. 이 형태들은 절을 닫을 때만 부정으로서 신뢰할 수 있다.
 * 절 중간에서는 증상 서술의 일부인 경우가 잦다(없어지다 = 사라지다,
 * 않다 가 더 긴 종속절 안에 들어간 경우).
 */
const CLAUSE_FINAL_NEGATIONS: readonly RegExp[] = [
  // 없다 계열: 없습니다 / 없어요 / 없고 / 없으며 / 없네요 / 없는데
  /없(습니다|어요|다|음|고|으며|네요|는데|었습니다|었어요|으신가요)?$/,
  // 않다 계열: 않았습니다 / 않아요 / 않았고 / 않은 / 않네요
  /않(습니다|아요|았습니다|았어요|았고|았어|은|네요|았습니다만)?$/,
  // 아니다 계열
  /아니(요|에요|오|었습니다|었어요)?$|아닙니다$|아녜요$/,
  // 못 + 지각/경험 동사: 못 들었어요 / 못 봤습니다 / 못 느꼈어요
  /못\s*(들었|봤|보았|했|한|느꼈|느낀|겪)[^\s]{0,6}$/,
  // 안 그래요 / 안 그렇습니다
  /안\s*그(래요|렇습니다|랬어요|런데요)?$/
];

/**
 * 경험 부정. 절 어디에 있든 명백하다.
 * "다친 적은 없습니다", "수술 받은 적 없어요" — 적(이|은) 없 구문에는
 * 긍정 독해가 없으므로 절 끝 앵커가 필요 없다.
 */
const EXPERIENCE_NEGATION = /적\s*(이|은|도)?\s*없/;

/** 절이 증상 보고가 아니라 부정으로 읽히면 true. */
export function isNegatedClause(clause: string): boolean {
  const trimmed = clause.replace(TRAILING_NOISE, '').trim();
  if (trimmed === '') return false;

  if (EXPERIENCE_NEGATION.test(trimmed)) return true;

  return CLAUSE_FINAL_NEGATIONS.some((pattern) => pattern.test(trimmed));
}

/**
 * 환자 답변 하나에서 부정된 절들을 제거한다.
 *
 * 살아남은 절은 공백으로 다시 이어붙인다 — 같은 답변의 서로 다른(부정되지 않은)
 * 절에 조각이 흩어진 다증상 패턴도 여전히 매치되도록. 환자가 부정만 말했다면
 * 빈 문자열이 나온다.
 */
export function stripNegatedClauses(utterance: string): string {
  return utterance
    .split(CLAUSE_BOUNDARY)
    .filter((clause) => clause.trim() !== '' && !isNegatedClause(clause))
    .map((clause) => clause.trim())
    .join(' ')
    .trim();
}
