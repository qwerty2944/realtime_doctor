/**
 * 환자에게 보이는 AI 고지 (배포구조·책임등급 문서 5장).
 *
 * 왜 동의문(`./consent.ts`)과 따로인가
 * ------------------------------------
 * 동의문은 "무엇에 동의하는가" 를 법적 문장으로 적은 것이고, 읽히기보다
 * 체크된다. 5장이 요구하는 것은 그것과 다르다 — **환자가 처음 보는 화면에서
 * 평이한 말로**, 접어두지 않고, 체크박스 없이 그냥 보이는 세 문장이다.
 * 동의 항목 안에 넣으면 "약관 전문 보기" 뒤로 접혀 들어가고, 접힌 경고는
 * 경고가 아니다.
 *
 * 그래서 이 문구는 동의 단계 **위에** 항상 펼쳐진 채로 붙고, 코드 입력 화면
 * (QR 로 들어오지 않은 환자가 처음 보는 화면)에도 같이 붙는다.
 *
 * 왜 서버에서 만들어 내려보내는가
 * -------------------------------
 * 동의문과 같은 이유다(`app/intake/page.tsx` 참고). 이건 고지이고, 고지가
 * 실제로 화면에 내려갔는지는 검증 대상이어야 한다. 서버 payload 에 담겨
 * 있으면 프로브가 그것을 단언할 수 있다 — 컴포넌트 안에 문자열로 박아두면
 * 렌더링을 눈으로 보는 것 말고는 확인할 방법이 없고, 이 머신에는 화면 캡처
 * 권한이 없다.
 *
 * [HARD] 문구는 세 가지를 반드시 말한다. 줄이지 않는다.
 *   1. 상대는 사람이 아니라 AI 이고, 여기서 나온 것은 진단이 아니다
 *   2. 진료 시작 전에 의사가 이 내용을 읽는다
 *   3. 응급 증상이면 문진을 멈추고 즉시 직원을 부른다 — AI 의 판정을
 *      기다리지 않는다
 *
 * 3번이 가장 중요하다. 키오스크는 red flag 를 판정하지만 그 판정은 대화가
 * 끝나가야 나오고, 그 사이 환자는 "이 기계가 위험하면 알려주겠지" 라고
 * 생각하며 앉아 있게 된다. 그 오해가 이 화면에서 만들어지는 가장 큰 위해다.
 */

export type IntakeDisclosureTone = 'info' | 'urgent';

export interface IntakeDisclosureItem {
  key: 'ai' | 'review' | 'emergency';
  tone: IntakeDisclosureTone;
  /** 굵게 나가는 한 줄. */
  headline: string;
  /** 그 아래 설명. 어르신이 소리내 읽어도 걸리지 않는 문장으로. */
  body: string;
}

export interface IntakeDisclosure {
  title: string;
  items: readonly IntakeDisclosureItem[];
}

export function buildIntakeDisclosure(): IntakeDisclosure {
  return {
    title: '문진을 시작하기 전에 꼭 읽어 주세요',
    items: [
      {
        key: 'ai',
        tone: 'info',
        headline: '지금부터 대화하는 상대는 사람이 아니라 AI입니다.',
        body:
          '컴퓨터가 자동으로 질문을 만들어 여쭙습니다. 여기서 나오는 말은 참고용 정리이며 ' +
          '진단이 아닙니다. 병명을 확인해 드리는 것도 아닙니다.'
      },
      {
        key: 'review',
        tone: 'info',
        headline: '작성하신 내용은 담당 의사가 직접 읽고 확인합니다.',
        body:
          '진료를 시작하기 전에 의사가 문진 내용을 확인합니다. ' +
          '진단과 치료에 대한 판단은 처음부터 끝까지 의사가 합니다.'
      },
      {
        key: 'emergency',
        tone: 'urgent',
        headline: '지금 많이 아프시면 문진을 멈추고 직원을 불러 주세요.',
        body:
          '가슴이 심하게 아프거나, 숨쉬기가 몹시 힘들거나, 의식이 흐려지거나, ' +
          '갑자기 한쪽 팔다리에 힘이 빠지거나 말이 어눌해진 경우에는 ' +
          '문진을 계속하지 마시고 지금 바로 직원에게 말씀해 주세요. ' +
          'AI가 위험하다고 알려줄 때까지 기다리지 마십시오.'
      }
    ]
  } as const;
}
